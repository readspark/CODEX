let levelCounter = 0;

export const CURRICULUM: CurriculumItem[] = RAW_CURRICULUM.map((raw, idx) => {
  const levelNumber = raw.ty === 'a' ? 0 : ++levelCounter;
  let startPos: [number, number, number] | undefined;
  if (raw.ty === 'g' && raw.map) {
    raw.map.forEach((rowStr, rIdx) => {
      const colIdx = rowStr.indexOf('S');
      if (colIdx > -1) {
        startPos = [rIdx, colIdx, 0];
      }
    });
  }

  return {
    index: idx,
    moduleIndex: Math.floor(idx / 9),
    levelNumber,
    pillar: raw.k,
    title: raw.t,
    type: raw.ty,
    concept: raw.c,
    question: raw.q,
    hint: raw.h ?? '',
    nudgeHint: raw.nudge,
    items: raw.i,
    sequenceExplanation: raw.seqExp,
    map: raw.map,
    maxBlocks: raw.max,
    parBlocks: raw.par,
    allowLoops: Boolean(raw.lp),
    startPos,
    code: raw.code,
    options: raw.o,
    correctIndex: raw.a,
    explanation: raw.e,
    optionFeedback: raw.optFb,
    questions: raw.qs,
  };
});

